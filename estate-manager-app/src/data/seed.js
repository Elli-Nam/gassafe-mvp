function floorCylinder(args) {
  return {
    id: args.id,
    serial: args.serial,
    footRingSerial: args.serial,
    qrSerial: args.serial,
    kind: args.kind, // HOME | COMMERCIAL
    sizeKg: args.sizeKg,
    tareKg: args.tareKg,
    grossKg: args.grossKg, // live scale reading
    status: args.status, // LEAK | BURST | IN_USE | SMOKE | FLAME
    batteryPct: args.batteryPct,
    loraRssiDbm: args.loraRssiDbm,
    calibration: args.calibration || "OK",
    cylinderTempC: args.cylinderTempC ?? 27,
    flameOn: args.flameOn ?? false,
    flameOnMinutes: args.flameOnMinutes ?? 0,
    gasPpm: args.gasPpm ?? 120,
    lastSeenSec: args.lastSeenSec ?? 8,
    avgDailyKg: args.avgDailyKg ?? 0.8,
    weightChangedRecently: args.weightChangedRecently ?? true,
    photoProof: {
      sameFrame: true,
      footStamp: args.serial,
      qrPlate: args.serial,
      note: "Combined photo: foot-ring stamp + QR plate in the same frame",
    },
    refill: args.refill || { state: null },
    history: args.history || [],
  };
}

